package com.oraltrainer.feedback.entity;

/**
 * Cycle de vie d'un feedback.
 * GENERATED : produit automatiquement après l'analyse.
 * VALIDATED : validé par un formateur sans modification des scores.
 * ADJUSTED  : validé par un formateur avec ajustement d'au moins un score.
 */
public enum FeedbackStatus {
    GENERATED,
    VALIDATED,
    ADJUSTED
}
